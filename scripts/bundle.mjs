#!/usr/bin/env node
/**
 * Zero-dependency bundler: turns the browser ES modules in src/ into one
 * classic script (dist/app.bundle.js).
 *
 * Why: Chromium-based browsers refuse to load ES modules from file:// URLs,
 * but the calculator should work by simply opening index.html. index.html
 * loads src/ui.js as a module over http(s) and this bundle on file://.
 *
 * Each module is wrapped in its own function scope (no name clashes);
 * `import { a, b as c } from './x.js'` becomes a destructuring of the
 * module's exports. Only the syntax used in src/ is supported:
 * named imports and `export function|const`.
 *
 * Usage: node scripts/bundle.mjs           (write dist/app.bundle.js)
 *        node scripts/bundle.mjs --check   (exit 1 if the file is stale)
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = 'src/ui.js';
const OUT = 'dist/app.bundle.js';

const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*$/gm;
const EXPORT_RE = /^export\s+(?:async\s+)?(function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;

const order = [];
const seen = new Set();

function resolve(from, spec) {
  if (!spec.startsWith('.')) throw new Error(`bare import "${spec}" in ${from} is not supported`);
  return posix.normalize(posix.join(posix.dirname(from), spec));
}

function visit(file) {
  if (seen.has(file)) return;
  seen.add(file);
  const src = readFileSync(join(root, file), 'utf8');
  for (const m of src.matchAll(IMPORT_RE)) visit(resolve(file, m[2]));
  order.push({ file, src });
}

function transform({ file, src }) {
  const exports = [...src.matchAll(EXPORT_RE)].map((m) => m[2]);
  const body = src
    .replace(IMPORT_RE, (_, names, spec) => {
      const binds = names.split(',').map((n) => n.trim()).filter(Boolean)
        .map((n) => n.replace(/^([\w$]+)\s+as\s+([\w$]+)$/, '$1: $2'));
      return `const { ${binds.join(', ')} } = __modules[${JSON.stringify(resolve(file, spec))}];`;
    })
    .replace(/^export\s+(?=(async\s+)?(function|const|let|class)\b)/gm, '');
  if (/^\s*export\b/m.test(body) || /^\s*import\b/m.test(body)) {
    throw new Error(`${file}: unsupported import/export syntax`);
  }
  return `// ---- ${file} ----\n__modules[${JSON.stringify(file)}] = (function () {\n${body.trimEnd()}\nreturn { ${exports.join(', ')} };\n})();\n`;
}

visit(ENTRY);
const out = `/* GENERATED by scripts/bundle.mjs from src/*.js — do not edit by hand. Run: npm run bundle */\n`
  + `(function () {\n'use strict';\nconst __modules = {};\n${order.map(transform).join('\n')}})();\n`;

const outPath = join(root, OUT);
if (process.argv.includes('--check')) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current !== out) {
    console.error(`${OUT} is out of date. Run "npm run bundle" and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${order.length} modules).`);
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, out);
  console.log(`wrote ${OUT} (${order.length} modules: ${order.map((o) => o.file).join(', ')})`);
}
